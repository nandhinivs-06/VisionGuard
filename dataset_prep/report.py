"""Step 5 - Write a dataset summary report (data/metadata/dataset_report.md) for the team.

    python -m dataset_prep.report
"""
import statistics
from collections import Counter

from .common import FRAMES_CSV, METADATA_DIR, NEGATIVE, POSITIVE, SPLITS, SPLITS_CSV, VIDEOS_CSV, read_csv, require

REPORT = METADATA_DIR / "dataset_report.md"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main(argv=None):
    require(VIDEOS_CSV, "run `python -m dataset_prep.organize` first")
    videos = read_csv(VIDEOS_CSV)
    lines = ["# Fire & smoke dataset report", "", "Generated by `python -m dataset_prep.report`.", ""]

    labels = Counter(r["label"] for r in videos)
    if videos and "source" in videos[0]:
        by_src = sorted({r["source"] for r in videos})
        lines += ["## Video sources", "", table(["source", "positive", "negative"],
                  [[s, sum(r["source"] == s and r["label"] == POSITIVE for r in videos),
                    sum(r["source"] == s and r["label"] == NEGATIVE for r in videos)] for s in by_src]), ""]
    dur = [float(r["duration_sec"]) for r in videos if r["readable"] == "True"]
    lines += ["## Videos", "", table(["total", "positive (fire/smoke)", "negative", "unknown", "total hours"],
              [[len(videos), labels[POSITIVE], labels[NEGATIVE], labels["unknown"], f"{sum(dur) / 3600:.2f}"]]), ""]
    if dur:
        lines += [f"Duration (s): min {min(dur):.0f}, median {statistics.median(dur):.0f}, max {max(dur):.0f}", ""]
    starts = [float(r["fire_start_sec"]) for r in videos if r["fire_start_sec"]]
    if starts:
        lines += [f"Fire start time (s): min {min(starts):.0f}, median {statistics.median(starts):.0f}, "
                  f"max {max(starts):.0f}; fire visible from frame 0 in {sum(s == 0 for s in starts)} videos", ""]
    res = Counter(f"{r['width']}x{r['height']}" for r in videos)
    fps = Counter(str(round(float(r["fps"]))) for r in videos)
    lines += ["Most common resolutions: " + ", ".join(f"{k} ({v})" for k, v in res.most_common(6)), "",
              "Frame rates: " + ", ".join(f"{k} fps ({v})" for k, v in sorted(fps.items(), key=lambda x: -x[1])), ""]
    notes = [r for r in videos if r["note"]]
    if notes:
        lines += ["### Videos needing attention", "", table(["video", "note"], [[r["filename"], r["note"]] for r in notes]), ""]

    if SPLITS_CSV.exists():
        sp = read_csv(SPLITS_CSV)
        rows = []
        for s in SPLITS:
            sr = [r for r in sp if r["split"] == s]
            rows.append([s, len(sr), sum(r["label"] == POSITIVE for r in sr), sum(r["label"] == NEGATIVE for r in sr),
                         f"{sum(float(r['duration_sec']) for r in sr) / 3600:.2f}"])
        lines += ["## Train / val / test split (video level)", "",
                  table(["split", "videos", "positive", "negative", "hours"], rows), ""]

    if FRAMES_CSV.exists():
        fr = read_csv(FRAMES_CSV)
        rows = []
        for s in SPLITS:
            c = Counter(r["frame_label"] for r in fr if r["split"] == s)
            rows.append([s, sum(c.values()), c["fire"], c["no_fire"], c["uncertain"]])
        lines += ["## Extracted frames", "", table(["split", "frames", "fire", "no_fire", "uncertain"], rows), ""]

    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"\nWrote {REPORT}")


if __name__ == "__main__":
    main()
